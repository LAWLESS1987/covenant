#!/usr/bin/env python3
"""tools/lookback_index.py -- one index of the record and its tombstones, for looking back. (A363, 2026-10-17)

WHY. The operator, 2026-10-17: "You should probably start some type of indexing system including for the
tombstones to make look back more efficient for yourself and other systems."

Looking back meant reading docs/KNOWN_ISSUES.md, over 15,000 lines and more than 360 entries in mixed order,
or grepping it and treating a hit as a fact (the derived-source error). The same day I answered a question
about the record from a grep hit and got it wrong twice (A362). The tombstones in docs/RETRACTED.json were
already listed in docs/CORRECTIONS.md (tools/corrections_index.py). Nothing tied a tombstone to the entry
that made it, and no single page let a system find the right entry before opening it.

WHAT IT MAKES. docs/LOOKBACK_INDEX.md, generated, never hand-edited:
  - every tombstone: its id, the entry that made it, the claim and the truth (shortened);
  - every record entry, highest number first: its id, the first date in its header, a status word if the
    header carries one, the tombstones it made, and the header's title (shortened).
No line numbers: KNOWN_ISSUES grows at the top, so line numbers would churn on every commit. `find` gives
live line numbers.

    python tools/lookback_index.py              # print the index
    python tools/lookback_index.py --write      # rewrite docs/LOOKBACK_INDEX.md
    python tools/lookback_index.py --check      # exit 1 when the file is missing or out of date
    python tools/lookback_index.py find WORD..  # entries and tombstones whose text has every word, with live
                                                # line numbers in KNOWN_ISSUES -- a POINTER: open the line

WHAT IT CANNOT SEE. It reads headers, not bodies: an entry whose header does not name its subject will not
be found by `find` on that subject (search the bodies with Grep, then open the line). Status is only what
the header says; many headers say none, and a header's status can be stale where the body was updated.
LICENCE: public domain.
"""
from __future__ import annotations

import json
import os
import re
import sys

HERE = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
RECORD = os.path.join(HERE, "docs", "KNOWN_ISSUES.md")
LEDGER = os.path.join(HERE, "docs", "RETRACTED.json")
INDEX = os.path.join(HERE, "docs", "LOOKBACK_INDEX.md")

HEAD = re.compile(r"^### (A\d+[a-z]?)\.\s*(.*)$")
DATE = re.compile(r"\b(20\d\d-\d\d-\d\d)\b")
STATUS = re.compile(r"\b(OPEN|FIXED|CLOSED|RESOLVED|UNDETERMINED|WONTFIX|SUPERSEDED|IN FLIGHT)\b")
BASE = re.compile(r"^(A\d+[a-z]?)")
TITLE_MAX = 170
CLAIM_MAX = 150


def _short(s, n):
    s = re.sub(r"\s+", " ", (s or "")).strip().replace("|", "\\|")
    return s if len(s) <= n else s[: n - 1].rstrip() + "…"


def _title(rest):
    m = re.match(r"\[(.*?)\]", rest)
    return m.group(1) if m else rest


def entries(text):
    """Every '### A<n>.' header: (id, line, date, status, title). Repeated ids are kept, each once per header."""
    out = []
    for i, line in enumerate(text.splitlines(), 1):
        m = HEAD.match(line)
        if not m:
            continue
        rid, rest = m.group(1), m.group(2)
        d, s = DATE.search(rest), STATUS.search(rest)
        out.append({"id": rid, "line": i, "date": d.group(1) if d else "",
                    "status": s.group(1) if s else "", "title": _title(rest)})
    return out


def tombstones(ledger, ids=None):
    """Each tombstone with the entry that made it. Given the record's header ids, a sub-id like A348d falls back
    to A348 when no A348d header exists, and an entry with no header at all is marked '(no header)'."""
    out = []
    for r in ledger.get("retractions", []):
        b = BASE.match(r.get("id", ""))
        entry = b.group(1) if b else ""
        if ids is not None and entry and entry not in ids:
            parent = entry.rstrip("abcdefghijklmnopqrstuvwxyz")
            entry = parent if parent in ids else entry + " (no header)"
        out.append({"id": r.get("id", ""), "entry": entry,
                    "claim": r.get("claim", ""), "truth": r.get("truth", "")})
    return out


def _num(rid):
    m = re.match(r"A(\d+)([a-z]?)", rid)
    return (int(m.group(1)), m.group(2)) if m else (0, "")


def render(text, ledger):
    es = entries(text)
    ts = tombstones(ledger, {e["id"] for e in es})
    by_entry = {}
    for t in ts:
        by_entry.setdefault(t["entry"], []).append(t["id"])
    lines = [
        "# Lookback index: the record and its tombstones",
        "",
        "Generated by `tools/lookback_index.py` from `docs/KNOWN_ISSUES.md` and `docs/RETRACTED.json`."
        " Edit those, never this file. The pre-commit hook regenerates it, and `test_li1_lookback_index.py`"
        " fails while it is stale.",
        "",
        "This index is a map, not the record. Open the entry before citing it. Live line numbers come from"
        " `python tools/lookback_index.py find WORD...`. Some entries rest on data in `private/`, which a"
        " reader cannot open; the entry says so where it matters.",
        "",
        "Counts: %d record headers, %d distinct ids, %d tombstones." % (
            len(es), len({e["id"] for e in es}), len(ts)),
        "",
        "## Tombstones (docs/RETRACTED.json), in ledger order",
        "",
        "| tombstone | entry | claim retracted | what is true |",
        "|---|---|---|---|",
    ]
    for t in ts:
        lines.append("| %s | %s | %s | %s |" % (t["id"], t["entry"] or "-",
                                                _short(t["claim"], CLAIM_MAX), _short(t["truth"], CLAIM_MAX)))
    lines += ["", "## Record entries (docs/KNOWN_ISSUES.md), highest number first", "",
              "| entry | date | status | tombstones | title |", "|---|---|---|---|---|"]
    for e in sorted(es, key=lambda e: (_num(e["id"]), -e["line"]), reverse=True):
        lines.append("| %s | %s | %s | %s | %s |" % (e["id"], e["date"] or "-", e["status"] or "-",
                                                     ", ".join(by_entry.get(e["id"], [])) or "-",
                                                     _short(e["title"], TITLE_MAX)))
    return "\n".join(lines) + "\n"


def _load():
    with open(RECORD, encoding="utf-8") as f:
        text = f.read()
    with open(LEDGER, encoding="utf-8") as f:
        ledger = json.load(f)
    return text, ledger


def find(words, text, ledger):
    ws = [w.lower() for w in words]
    hits = []
    for e in entries(text):
        if all(w in (e["id"] + " " + e["title"]).lower() for w in ws):
            hits.append("KNOWN_ISSUES.md line %d  %s  %s  %s" % (e["line"], e["id"], e["date"] or "-",
                                                                 _short(e["title"], 120)))
    for t in tombstones(ledger, {e["id"] for e in entries(text)}):
        if all(w in " ".join((t["id"], t["claim"], t["truth"])).lower() for w in ws):
            hits.append("RETRACTED.json  %s (entry %s)  %s" % (t["id"], t["entry"] or "-", _short(t["claim"], 120)))
    return hits


def main(argv):
    text, ledger = _load()
    want = render(text, ledger)
    if argv[:1] == ["find"]:
        hits = find(argv[1:], text, ledger)
        print("\n".join(hits) if hits else "no header or tombstone has all of: %s (headers only; bodies are not searched)" % " ".join(argv[1:]))
        return 0
    if "--write" in argv:
        with open(INDEX, "w", encoding="utf-8", newline="\n") as f:
            f.write(want)
        print("lookback_index: wrote docs/LOOKBACK_INDEX.md")
        return 0
    if "--check" in argv:
        try:
            with open(INDEX, encoding="utf-8") as f:
                have = f.read()
        except OSError:
            print("lookback_index: docs/LOOKBACK_INDEX.md is missing")
            return 1
        if have != want:
            print("lookback_index: docs/LOOKBACK_INDEX.md is out of date -- run python tools/lookback_index.py --write")
            return 1
        print("lookback_index: current")
        return 0
    sys.stdout.write(want)
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
